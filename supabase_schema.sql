SET name = EXCLUDED.name, yandex_folder = EXCLUDED.yandex_folder;

-- 2. Таблица Dialogs (Диалоги и оценки)
CREATE TABLE IF NOT EXISTS public.dialogs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint REFERENCES public.shops(id) ON DELETE CASCADE,
    dialog_index integer NOT NULL,
    original_audio_file text,
    clean_text text,
    speakers_involved text[] DEFAULT '{}'::text[],
    transcript jsonb DEFAULT '[]'::jsonb,
    score numeric(3,1), -- оценка от 0.0 до 5.0
    text_analysis text,
    audio_url text,
    lost_revenue_rub numeric DEFAULT 0,
    audit_details jsonb DEFAULT '{}'::jsonb,
    tags text[] DEFAULT '{}'::text[],
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Таблица App Status (Статус оркестратора)
CREATE TABLE IF NOT EXISTS public.app_status (
    id bigint PRIMARY KEY,
    is_analyzing boolean DEFAULT false,
    status_message text,
    last_run_at timestamp with time zone
);

