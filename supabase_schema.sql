-- Разрешаем публичный доступ (RFE-политики) для удобства тестирования
ALTER TABLE public.shops ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dialogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.agent_telemetry ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow anonymous read shops" ON public.shops FOR SELECT USING (true);
CREATE POLICY "Allow anonymous read dialogs" ON public.dialogs FOR SELECT USING (true);
CREATE POLICY "Allow anonymous read app_status" ON public.app_status FOR SELECT USING (true);
CREATE POLICY "Allow anonymous read agent_telemetry" ON public.agent_telemetry FOR SELECT USING (true);

-- Разрешаем запись для service_role / anon (если без RLS для тестов)
