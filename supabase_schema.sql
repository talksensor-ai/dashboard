-- 1. Таблица Shops (Магазины/Кофейни)
CREATE TABLE IF NOT EXISTS public.shops (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    yandex_folder text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

